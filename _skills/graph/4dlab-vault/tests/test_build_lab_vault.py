import subprocess
import sys
import tempfile
import unittest
from pathlib import Path


SCRIPT = Path(__file__).resolve().parents[1] / "scripts" / "build_lab_vault.py"


def write(path: Path, text: str = "") -> None:
    path.parent.mkdir(parents=True, exist_ok=True)
    path.write_text(text, encoding="utf-8")


def seed_lab(repo: Path, lab: str, *, include_prose_graphs: bool) -> Path:
    lab_root = repo / "labs" / lab
    write(lab_root / lab / "__init__.py")
    write(lab_root / "tests" / "test_smoke.py")
    write(lab_root / "wiki" / "00_index.md", "# Index\n")
    write(lab_root / "docs" / "PRD.md", "# PRD\n")
    write(lab_root / "graph" / "v2_code" / "graph.json", '{"nodes":[{}],"links":[]}')
    write(lab_root / "graph" / "v2_tests" / "graph.json", '{"nodes":[{}],"links":[]}')
    if include_prose_graphs:
        write(lab_root / "graph" / "v2_wiki" / "graph.json", '{"nodes":[{}],"links":[]}')
        write(lab_root / "graph" / "v2_docs" / "graph.json", '{"nodes":[{}],"links":[]}')
    return lab_root


def seed_assets(root: Path, lab: str) -> Path:
    assets = root / "assets"
    write(
        assets / f"vault-map.{lab}.yaml",
        f"module: {lab}\nframe: {{}}\n",
    )
    write(assets / "lab-landing.md.tmpl", "# {{LAB}}\n{{MODULE}}\n")
    return assets


class BuildLabVaultEligibilityTests(unittest.TestCase):
    def test_gaslab_dry_run_allows_missing_waived_prose_graphs(self) -> None:
        with tempfile.TemporaryDirectory() as td:
            root = Path(td)
            repo = root / "repo"
            repo.mkdir()
            assets = seed_assets(root, "gaslab")
            seed_lab(repo, "gaslab", include_prose_graphs=False)

            result = subprocess.run(
                [
                    sys.executable,
                    str(SCRIPT),
                    "--lab",
                    "gaslab",
                    "--repo",
                    str(repo),
                    "--assets",
                    str(assets),
                    "--dry-run",
                ],
                text=True,
                capture_output=True,
                check=False,
            )

            self.assertEqual(result.returncode, 0, result.stderr + result.stdout)
            self.assertIn("build vault for 'gaslab'", result.stdout)

    def test_non_gaslab_still_requires_all_four_graph_tiers(self) -> None:
        with tempfile.TemporaryDirectory() as td:
            root = Path(td)
            repo = root / "repo"
            repo.mkdir()
            assets = seed_assets(root, "obdlab")
            seed_lab(repo, "obdlab", include_prose_graphs=False)

            result = subprocess.run(
                [
                    sys.executable,
                    str(SCRIPT),
                    "--lab",
                    "obdlab",
                    "--repo",
                    str(repo),
                    "--assets",
                    str(assets),
                    "--dry-run",
                ],
                text=True,
                capture_output=True,
                check=False,
            )

            self.assertNotEqual(result.returncode, 0)
            self.assertIn("v2_wiki", result.stderr + result.stdout)
            self.assertIn("v2_docs", result.stderr + result.stdout)

    def test_lab_build_preserves_existing_provenance_sections(self) -> None:
        with tempfile.TemporaryDirectory() as td:
            root = Path(td)
            repo = root / "repo"
            repo.mkdir()
            assets = seed_assets(root, "gaslab")
            seed_lab(repo, "gaslab", include_prose_graphs=False)
            existing = repo / "Vault" / "_meta" / "PROVENANCE.md"
            write(
                existing,
                "# Vault provenance\n\n"
                "Generated by build_lab_vault.py.\n\n"
                "## obdlab\n"
                "- built: 2026-06-11\n"
                "- source: `labs/obdlab/`\n",
            )

            result = subprocess.run(
                [
                    sys.executable,
                    str(SCRIPT),
                    "--lab",
                    "gaslab",
                    "--repo",
                    str(repo),
                    "--assets",
                    str(assets),
                ],
                text=True,
                capture_output=True,
                check=False,
            )

            self.assertEqual(result.returncode, 0, result.stderr + result.stdout)
            provenance = existing.read_text(encoding="utf-8")
            self.assertIn("## obdlab", provenance)
            self.assertIn("## gaslab", provenance)


if __name__ == "__main__":
    unittest.main()
